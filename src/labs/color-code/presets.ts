export interface Initial {
  mode: Mode;
  bandCount: BandCount;
  bands: ColourName[];
  target: number;
  smdCode: string;
}

export function initialFor(preset: string): Initial {
  const base: Initial = { mode: "read", bandCount: 4, bands: ["yellow", "violet", "red", "gold"], target: 2200, smdCode: "472" };
  switch (preset) {
    case "make":
      return { ...base, mode: "make", bands: ["brown", "black", "red", "gold"] };
    case "quiz":
      return { ...base, mode: "quiz" };
    case "five-band":
      return { ...base, bandCount: 5, bands: ["brown", "black", "black", "red", "brown"] };
    case "smd":
      return { ...base, mode: "smd" };
    default:
      return base;
  }
}

